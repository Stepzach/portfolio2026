let language = 'en';
try { language = localStorage.getItem('atable-language') === 'fr' ? 'fr' : 'en'; } catch {}
export const getLanguage = () => language;
export const dateLocale = () => language === 'fr' ? 'fr-FR' : 'en-GB';
export function setLanguage(value) {
  language = value === 'fr' ? 'fr' : 'en';
  try { localStorage.setItem('atable-language', language); } catch {}
}
export function t(text, values = {}) {
  return (language === 'fr' ? french[text] ?? text : text).replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match);
}
export function localizePlace(place) {
  if (!place || language === 'en') return place;
  return {...place, ...notes[place.id], category:t(place.category), address:t(place.address), metro:t(place.metro)};
}
export function areaText(place) {
  if (place.city !== 'paris' || place.area === 'Multiple locations') return t(place.area);
  const area = language === 'fr' ? place.area.replace(/(\d+)(?:st|nd|rd|th)/, (_, n) => n + (n === '1' ? 'er' : 'e')) : place.area;
  return `${area} arrondissement`;
}
export function translatePage() {
  document.documentElement.lang = language;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  for (const attribute of ['aria-label', 'title', 'content']) {
    document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(el => el.setAttribute(attribute, t(el.getAttribute(`data-i18n-${attribute}`))));
  }
  document.querySelectorAll('[data-lang]').forEach(button => {
    const selected = button.dataset.lang === language;
    button.classList.toggle('selected', selected);
    button.setAttribute('aria-pressed', selected);
  });
}
